/// 灵感箱空着时轮换展示的那几句话（ADR-084）。
///
/// **为什么这里允许写"没用的话"**：《界面规范》§0 的规矩是"界面上不写说明性文字"
/// —— 判据是"删掉它用户会不会因此丢数据 / 找不到东西"。这十几句按那条判据**都该删**，
/// 所以它们是**明写的例外**，口子只开在"灵感箱空态"这一处，别处照旧。
///
/// 为什么灵感箱可以例外：它是这个应用里**最常看到、又最无话可说**的一屏 ——
/// 灵感箱空着是**好状态**（该记的都记完了），而一个光秃秃的"空"字像是出了故障。
/// 换一句话说，这里需要的不是信息，是"没事，空着挺好"。
///
/// 展示规则（与 ADR-084 一致）：
///   · **每次启动抽一次，本次会话固定** —— 切页签、返回、重建都不变；
///     每次进这一页都换一句会晃眼，而且用户会开始怀疑自己看错了；
///   · 抽签结果以**种子**的形式存在 `ui_prefs`（`emptyBoxSeed`），
///     所以测试可以给死种子，断言稳定。
library;

/// 灵感的空箱文案表。**加句子往后面接**，不要动已经有的顺序 ——
/// 顺序变了，同一个种子在不同版本上会落到不同句子（无害，但没必要）。
const List<String> emptyBoxLines = <String>[
  '这里比手术室都干净',
  '开动脑筋，实事求是',
  '这里比白纸还白，比空白还空。',
  '今天没有灵感？巧了，这里也没有',
  '脑洞打烊，创意补货中',
  '想法在路上，可能堵在脑回路',
  '屏幕干净得像刚格式化',
  '灵感去摸鱼了，归期未定',
  '当前状态：脑内暂无信号',
  '今日灵感已售罄，欢迎下次光临',
  '空白不是故障，是灵感还在加载',
  '脑细胞开了半天会，暂无结论',
  '先空着吧，下一个念头正在赶来',
  '灵感箱是空的！空的！！！',
  '这里空的要命，真的',
];

/// 按种子取那一句。种子是任意整数（`null` 时用 0 —— 正常路径上不会为 null，
/// 界面在首帧就把种子落进偏好了）。
String emptyBoxLineFor(int? seed) {
  final index = (seed ?? 0) % emptyBoxLines.length;
  // Dart 的 `%` 对负数也给非负结果，但显式再兜一次：种子可能来自别处
  return emptyBoxLines[index < 0 ? index + emptyBoxLines.length : index];
}
