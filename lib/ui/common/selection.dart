/// 多选模式里那个**唯一有分叉风险的判断**：点"全选"之后该选中哪些 id。
///
/// ## 为什么只有这一个函数
///
/// 「长按进入多选、点条目切换、全选作用于当前可见项」这套状态机在四个页面里各写了一遍
/// （灵感页 / 全部任务 / 搜索 / 项目详情页的待处理灵感）。四个页面的 `setState`、幽灵
/// 选中清理、动作条接线各不相同 —— 那是各页自己的事。但**"全选"这一步的判断是纯的**，
/// 也正是最容易各写各的、写完就漂的一格。
///
/// 所以这里只抽这一格：**状态仍归各页的 `State`**（`setState` 是 protected，
/// 而且"谁触发重建"是页面职责 —— 抽走它反而会多出"改了状态忘了 setState"这种
/// 静默失败）。抽出来的是一个可单测的纯函数，四个页面共用同一份判断。
///
/// ## 口径
///
/// - [visibleIds] 是**当前可见**的那些（已被筛选掉的不能进来）——
///   四个页面在这一格上必须给出同一个集合，否则"全选"在不同页面选中的条数不一样，
///   而用户正是照那个条数决定接着批量做什么。
/// - [selectedIds] 只用来判断"现在是不是已经全选"。
/// - 已经全选 → 返回空集（全选键第二次按是取消）；
///   否则 → 返回 [visibleIds] 的全部（**不是增量追加**：那样在"选了两个后又筛出别的"
///   时会留下筛选前选中的东西，与"只作用于当前可见项"矛盾）。
///
/// 判据用 `selectedIds.length == visibleIds.length` 而不是集合包含：
/// 那一格在四个页面里原来就是这么写的，**语义务必保持不变** ——
/// 幽灵选中（已不在可见项里的 id）由各页在 build 里清理，不归这里管。
Set<String> selectionAfterToggleAll({
  required Set<String> visibleIds,
  required Set<String> selectedIds,
}) {
  if (selectedIds.length == visibleIds.length) return <String>{};
  return <String>{...visibleIds};
}
