/// 项目标志色的色板（**唯一的定义处**）。
///
/// 放 core 而不是 ui，是因为有**两个**使用方，而它们不能互相依赖：
///   · `lib/ui` 的取色器要把它列出来让用户挑；
///   · `lib/features` 的 `Workspace` 要在新建项目时自动分配一个。
/// 架构约束是"features 不依赖 ui"（`test/core/architecture_test.dart` 守着），
/// 所以这份数据只能待在两边都能用的 core。
///
/// 色值取自用户给的 12 个 Hex：低饱和的灰调彩色，
/// 用来在小面积上互相区分，又不抢内容。
///
/// **16 色 = 原 12 色 + 追加的 4 色**（2026-09-26 批 B 第 ② 项）。
/// 追加是**纯加法**：前 12 个色值一个字节都没动（老数据零迁移、
/// 不升 `schemaVersion`），新色只往后接，界面取色器与 `Workspace` 的
/// "取用得最少的那支"都自动跟着变多。
///
/// ## 新色的挑选口径（可验证，见 `test/core/project_palette_test.dart`）
///
/// **度量**：把 sRGB 转成 CIELAB（D65 白点），两色距离取 **CIE76 ΔE**，
/// 也就是 Lab 三个分量上的欧氏距离
/// `ΔE = √(ΔL*² + Δa*² + Δb*²)`。
///
/// **阈值**：以**原 12 色里最接近的一对**为门槛 —— 那一对是
/// 松石 `#87C7AD` / 青 `#78D2CA`，ΔE ≈ **11.83**。
/// 要求"任意两色（含新旧之间）的 ΔE ≥ 11.83"，即**新色不会比原有色更难区分**；
/// 同时新色的 HSL **饱和度与明度必须落在原 12 色的区间内**
/// （S ∈ [0.2212, 0.5976]，L ∈ [0.5000, 0.8176]），保证还是同一套"灰调"。
///
/// 四个新色的色相分别补上原来最缺的四段：靛蓝 228°、橄榄 68°、
/// 咖棕 35°、青灰（石板）204°；它们离最近的原色分别有
/// ΔE ≈ 16.75（靛蓝 ↔ 灰紫）、17.86（橄榄 ↔ 麦黄）、
/// 15.84（咖棕 ↔ 赭）、18.86（青灰 ↔ 灰紫）。
abstract final class ProjectPalette {
  static const List<String> hexes = <String>[
    // 以下 12 个是**原始色板**，顺序与色值不可改（老数据靠它认色）。
    '#AD6868', // 陶红
    '#B87F56', // 赭
    '#DECF7C', // 麦黄
    '#CCE8B6', // 嫩绿
    '#87C57E', // 草绿
    '#87C7AD', // 松石
    '#78D2CA', // 青
    '#A9BFD5', // 雾蓝
    '#8280AE', // 灰紫
    '#DAC1E0', // 藕荷
    '#A56EA9', // 紫
    '#A85780', // 梅红

    // 以下 4 个是 2026-09-26 追加的（补色相，不动上面 12 个）。
    '#5A6BAF', // 靛蓝
    '#A2AD5C', // 橄榄
    '#A38A67', // 咖棕
    '#62869E', // 青灰（石板）
  ];
}
